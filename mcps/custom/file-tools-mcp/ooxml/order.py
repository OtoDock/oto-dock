"""The schema order of an OOXML element's children, and an insert that keeps it.

Office refuses a file whose children are out of schema order (a ``w:shd``
after ``w:noWrap`` in a cell's properties, a ``p:bg`` after the shape tree),
while python-docx, python-pptx and lxml append wherever they are told.
``insert_child`` places a new child where the schema wants it.

The order comes from ``order_table.json``, generated by
``generate_order.py`` from the Open XML SDK's schema data (MIT). An
element's type is found from its name, or, where one name has several types
(``w:rPr`` under ``w:pPr`` is not ``w:rPr`` under ``w:r``), from its parent's
type. Children the table does not know (another namespace's extension,
``mc:AlternateContent``) stay where they are and are never compared;
``extLst`` stays last.
"""

from __future__ import annotations

import functools
import json
from pathlib import Path
from typing import Any

TABLE_FILE = Path(__file__).with_name("order_table.json")
EXT_LIST = "extLst"


@functools.cache
def _table() -> tuple[dict[str, tuple[str, ...]], dict[str, str], dict[str, dict[str, tuple[int, ...]]],
                      dict[str, dict[str, str]]]:
    """(ambiguous name -> its types, unique name -> its type, type -> {child:
    its ranks}, type -> {ambiguous child: its type}), names in Clark
    notation. A child the sequence allows at several places has several
    ranks, lowest first."""
    raw = json.loads(TABLE_FILE.read_text(encoding="utf-8"))
    namespaces = raw["namespaces"]

    def clark(prefixed: str) -> str:
        prefix, _, local = prefixed.partition(":")
        return f"{{{namespaces[prefix]}}}{local}" if prefix in namespaces else local

    ambiguous = {clark(name): tuple(types) for name, types in raw["elements"].items()}
    unique: dict[str, str] = {}
    ranks: dict[str, dict[str, tuple[int, ...]]] = {}
    child_types: dict[str, dict[str, str]] = {}
    for type_name, rows in raw["types"].items():
        element = clark(type_name.split("/", 1)[1])
        if element not in ambiguous:
            unique[element] = type_name
        ranks[type_name] = {clark(row[0]): tuple(row[1]) for row in rows}
        child_types[type_name] = {clark(row[0]): row[2] for row in rows if len(row) > 2}
    return ambiguous, unique, ranks, child_types


@functools.cache
def _required() -> frozenset[str]:
    """The types whose content needs at least one child element."""
    return frozenset(json.loads(TABLE_FILE.read_text(encoding="utf-8")).get("required", ()))


def needs_children(element: Any) -> bool:
    """Whether the schema lets ``element`` hold no child element: False
    when it may be empty or its type is unknown. A name with several types
    whose parent does not tell them apart counts only when every one of
    them needs a child (an empty element gives no hint of its type)."""
    ambiguous, unique, _, child_types = _table()
    required = _required()
    tag = _tag(element)
    if tag is None:
        return False
    if tag not in ambiguous:
        return unique.get(tag) in required
    parent = element.getparent()
    parent_type = None if parent is None else type_of(parent)
    found = None if parent_type is None else child_types.get(parent_type, {}).get(tag)
    if found:
        return found in required
    return all(candidate in required for candidate in ambiguous[tag])


def _tag(element: Any) -> str | None:
    tag = element.tag
    return tag if isinstance(tag, str) else None


def type_of(element: Any) -> str | None:
    """The schema type of ``element`` (``w:CT_PPr/w:pPr``), or ``None``
    when the table does not know it."""
    ambiguous, unique, _, child_types = _table()
    tag = _tag(element)
    if tag is None:
        return None
    if tag not in ambiguous:
        return unique.get(tag)
    parent = element.getparent()
    parent_type = None if parent is None else type_of(parent)
    found = None if parent_type is None else child_types.get(parent_type, {}).get(tag)
    return found or _best_fit(element, ambiguous[tag])


def _best_fit(element: Any, candidates: tuple[str, ...]) -> str:
    """Of the types one name has, the one whose children cover the most of
    the element's own (a detached element, or one under an unknown parent)."""
    ranks = _table()[2]
    tags = [t for t in (_tag(c) for c in element) if t is not None]
    return max(candidates, key=lambda c: sum(t in ranks.get(c, {}) for t in tags))


def _all_ranks(parent: Any) -> dict[str, tuple[int, ...]] | None:
    parent_type = type_of(parent)
    return None if parent_type is None else _table()[2].get(parent_type)


def child_ranks(parent: Any) -> dict[str, int] | None:
    """``{child tag: rank}`` of ``parent``'s type, a child's first place
    where it has several, ``None`` when unknown."""
    ranks = _all_ranks(parent)
    return None if ranks is None else {tag: places[0] for tag, places in ranks.items()}


def _is_ext_list(tag: str | None) -> bool:
    return bool(tag) and tag.rsplit("}", 1)[-1] == EXT_LIST


def insert_child(parent: Any, child: Any) -> Any:
    """Insert ``child`` into ``parent`` where the schema orders it: before
    the first known sibling of a higher rank (a child with several places
    takes its first), else last (before a trailing ``extLst`` when the
    child is not one). Returns ``child``."""
    ranks = child_ranks(parent)
    tag = _tag(child)
    rank = None if ranks is None or tag is None else ranks.get(tag)
    for position, existing in enumerate(parent):
        existing_tag = _tag(existing)
        if existing_tag is None:
            continue
        if rank is None:
            if _is_ext_list(existing_tag) and not _is_ext_list(tag):
                parent.insert(position, child)
                return child
            continue
        existing_rank = ranks.get(existing_tag)
        if existing_rank is not None and existing_rank > rank:
            parent.insert(position, child)
            return child
    parent.append(child)
    return child


def out_of_order(parent: Any) -> list[tuple[str, str]]:
    """Each ``(child, sibling)`` pair where a known child comes after a
    known sibling the schema puts after it; unknown children are skipped.
    A child with several places takes the first one at or after the
    highest place seen so far (the earliest keeps the most room for the
    children after it)."""
    ranks = _all_ranks(parent)
    if not ranks:
        return []
    found: list[tuple[str, str]] = []
    highest: tuple[int, str] | None = None
    for existing in parent:
        tag = _tag(existing)
        places = None if tag is None else ranks.get(tag)
        if places is None:
            continue
        floor = -1 if highest is None else highest[0]
        rank = next((place for place in places if place >= floor), None)
        if rank is None:
            found.append((tag, highest[1]))
        elif rank > floor:
            highest = (rank, tag)
    return found
