_VERSION_RE = re.compile(r"(\d+)\.(\d+)")


def _major_minor(text: str) -> str:
    match = _VERSION_RE.search(text)
    return f"{match.group(1)}.{match.group(2)}" if match else ""


TABLES = {
    ("LibreOffice", _major_minor(ENGINE)): SUPPORTED,
    ("Collabora_Office", _major_minor(COLLABORA_ENGINE)): COLLABORA,
}
# What every known engine computes: the table for an engine of another
# version, or a file that names none.
EVERY_ENGINE = frozenset.intersection(*TABLES.values())


def supported_by(application: str | None) -> frozenset[str]:
    """The functions trusted in a workbook recalculated by the engine its
    ``Application`` names: that engine's table when the version is the one
    measured, else what every engine computes."""
    from render_engine import engine_of_application

    engine, version = engine_of_application(application)
    if engine is None:
        return EVERY_ENGINE
    return TABLES.get((engine.value, version), EVERY_ENGINE)
