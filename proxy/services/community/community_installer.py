# The package check — what the installer will say, without installing
# ---------------------------------------------------------------------------

_MASTER_KEY_TOKENS = ("${platform.api_key}", "${proxy_api_key}")
_ICON_SIZE = 256
_ICON_MAX_BYTES = 256 * 1024


def _icon_problem(path: Path) -> str | None:
    """Why ``icon.png`` is not the 256×256 PNG the catalog asks for; ``None``
    when it is (the signature and the IHDR chunk, no imaging library)."""
    try:
        size = path.stat().st_size
        with path.open("rb") as fh:
            head = fh.read(24)
    except OSError as exc:
        return f"cannot be read ({exc})"
    if size > _ICON_MAX_BYTES:
        return f"is {size} bytes (limit {_ICON_MAX_BYTES})"
    if head[:8] != b"\x89PNG\r\n\x1a\n" or head[12:16] != b"IHDR":
        return "is not a PNG"
    width = int.from_bytes(head[16:20], "big")
    height = int.from_bytes(head[20:24], "big")
    if (width, height) != (_ICON_SIZE, _ICON_SIZE):
        return f"is {width}x{height}, must be {_ICON_SIZE}x{_ICON_SIZE}"
    return None


def check_package(mcp_root: Path, *, skipped: list[str] | tuple[str, ...] = ()) -> dict:
    """What ``install_from_extracted_folder`` would refuse, drop or accept in
    ``mcp_root``, plus the catalog's conventions, without installing
    anything: ``{ok, errors, warnings, summary}``. The authoring check tool
    (``validate_mcp_package`` in mcps-mcp) runs it on a snapshot of the
    author's folder; ``skipped`` names the entries the snapshot left out
    (dotfiles, ``node_modules``, ``venv``), judged here since the copy never
    holds them. Synchronous: run it through ``asyncio.to_thread``."""
    from urllib.parse import urlsplit
    errors: list[str] = []
    warnings: list[str] = []

    for name in skipped:
        base = name.rsplit("/", 1)[-1]
        if base == ".env":
            errors.append(
                f"{name}: a .env file is refused at install; declare environment "
                "values in the manifest and keep secrets in instances or credentials",
            )
        elif base in _REFUSED_INCOMING_DIRS:
            errors.append(
                f"{name}: a {base} entry is refused at install; the platform "
                "installs dependencies itself from server.source",
            )
    for p in sorted(mcp_root.rglob("*")):
        rel = str(p.relative_to(mcp_root))
        if p.name == ".env" and p.is_file():
            errors.append(f"{rel}: a .env file is refused at install")
        elif p.name in _REFUSED_INCOMING_DIRS:
            errors.append(f"{rel}: a {p.name} entry is refused at install")
    for name in sorted(_DROPPED_INCOMING_FILES):
        if (mcp_root / name).exists():
            warnings.append(f"{name} is dropped at install (the platform resolves its own lock)")

    manifest_path = mcp_root / "manifest.json"
    if not manifest_path.is_file():
        errors.append("manifest.json not found at the package root")
        return {"ok": False, "errors": errors, "warnings": warnings, "summary": {}}
    try:
        raw = manifest_path.read_text()
        data = json.loads(raw)
    except (OSError, ValueError) as exc:
        errors.append(f"manifest.json is not valid JSON: {exc}")
        return {"ok": False, "errors": errors, "warnings": warnings, "summary": {}}
    if not isinstance(data, dict):
        errors.append("manifest.json must hold an object")
        return {"ok": False, "errors": errors, "warnings": warnings, "summary": {}}

    errors.extend(_validate_manifest(data))
    named = _mmp.agent_context_credential_tokens(data.get("agent_context"))
    if named:
        warnings.append(
            f"agent_context names {', '.join(named)}: no credential value enters "
            "a prompt, so each renders empty and a requires on one skips its block")
    server = data.get("server") if isinstance(data.get("server"), dict) else {}
    source = server.get("source", "") if isinstance(server.get("source", ""), str) else ""
    runtime = server.get("runtime", "")
    rt = _mt.runtime_of(runtime) if isinstance(runtime, str) else None
    remote = source.startswith("remote:")
    name = data.get("name", "")
    if isinstance(name, str) and name and not _is_safe_name(name):
        errors.append(f"name {name!r} must be lowercase letters, digits, dashes and underscores")
    if data.get("category") not in (None, "community"):
        errors.append("category must be \"community\" (core and custom ship with the platform)")
    if source and not remote and mcp_installer.parse_source(source) is None:
        errors.append(
            f"server.source {source!r} is not an accepted source (npm:<package>, "
            "pypi:<package>, git+<url>@<ref>, docker:<image>, remote:<host>)",
        )
    skills = data.get("skills") if isinstance(data.get("skills"), list) else []
    for sk in skills:
        if isinstance(sk, dict) and isinstance(sk.get("file"), str) and \
                _mmp.skill_file_error(sk["file"]) is None and \
                _mmp.resolve_skill_file(mcp_root, sk["file"]) is None:
            errors.append(f"skill {sk.get('id')}: file {sk['file']!r} is not a regular file inside the package")
    compose_file = server.get("docker_compose") or ""
    if rt is not None and rt.container:
        if not compose_file:
            errors.append("server.docker_compose must name the compose file of a docker MCP")
        elif isinstance(compose_file, str) and _mmp.skill_file_error(compose_file) is None and \
                _mmp.resolve_skill_file(mcp_root, compose_file) is None:
            errors.append(f"server.docker_compose {compose_file!r} is not a regular file inside the package")
        if not server.get("image"):
            warnings.append(
                "server.image is absent: the containerised deployment cannot build "
                "an image, so the package installs on bare metal only",
            )
        url_template = str(server.get("url_template") or "")
        if "${docker_mcp_host}" not in url_template:
            warnings.append(
                "server.url_template should be http://${docker_mcp_host}:${port}: a fixed "
                "host breaks the containerised deployment",
            )
        if not str(data.get("version") or ""):
            errors.append("version must be set for a docker MCP (the image tag)")
    if source.startswith("git+") and not str(data.get("version") or ""):
        errors.append("version must be set for a git+ source (the pinned ref)")
    if rt is not None and rt.installed and source and not source.startswith("git+"):
        parsed = mcp_installer.parse_source(source)
        if parsed is not None and parsed.version:
            warnings.append(
                f"server.source pins {parsed.version}: the catalog leaves node and "
                "python packages unpinned and the platform pins the installed version",
            )
    if rt is not None and rt.installed and runtime == _mt.RUNTIME_PYTHON and (mcp_root / "requirements.txt").is_file():
        warnings.append("requirements.txt is dropped at install: a python package installs from server.source")
    for block in ("env", "agent_env"):
        values = data.get(block)
        if isinstance(values, dict):
            for key in values:
                if str(key).startswith("OTO_") or str(key) in ("PROXY_URL", "PROXY_API_KEY"):
                    warnings.append(
                        f"{block}.{key}: the OTO_* set, PROXY_URL and PROXY_API_KEY are "
                        "injected by the platform and must not be declared",
                    )
    for token in _MASTER_KEY_TOKENS:
        if token in raw:
            errors.append(f"the manifest references the master key ({token}), which is never given to an MCP")
    if not (mcp_root / "README.md").is_file():
        warnings.append("README.md is missing: the catalog shows it in the install dialog")
    icon = mcp_root / "icon.png"
    if icon.is_file():
        problem = _icon_problem(icon)
        if problem:
            warnings.append(f"icon.png {problem}")
    if not str(data.get("author") or "").strip():
        warnings.append("author is missing: name the project whose server code the package wraps")
    author_url = str(data.get("author_url") or "")
    author_parts = urlsplit(author_url)
    if author_parts.scheme != "https" or not author_parts.netloc:
        warnings.append("author_url should be the https:// repository of the upstream project")
    if not errors:
        try:
            parsed_manifest = _mmp._parse_manifest(manifest_path)
        except ValueError as exc:
            errors.append(f"manifest block rejected: {exc}")
            parsed_manifest = None
        if parsed_manifest is None and not errors:
            errors.append("the manifest could not be parsed")
    if not errors and rt is not None and rt.container:
        try:
            _check_incoming_compose(mcp_root, str(name))
        except HTTPException as exc:
            errors.append(str(exc.detail))

    skills = [sk.get("id") for sk in skills if isinstance(sk, dict)]
    creds = data.get("credentials") if isinstance(data.get("credentials"), dict) else {}
    summary = {
        "name": name, "label": data.get("label", ""),
        "runtime": "remote" if remote and not runtime else runtime,
        "transport": server.get("transport", ""),
        "source": source, "version": data.get("version", ""),
        "credentials": creds.get("type", "none"),
        "instances": isinstance(data.get("instances"), dict),
        "skills": [s for s in skills if isinstance(s, str)],
        "host": urlsplit(str(server.get("url_template") or "")).hostname or "" if remote else "",
        "files": sum(1 for p in mcp_root.rglob("*") if p.is_file()),
    }
    return {"ok": not errors, "errors": errors, "warnings": warnings, "summary": summary}


# ---------------------------------------------------------------------------
# Folder install — shared between zip-upload and tarball-fetch
# ---------------------------------------------------------------------------

async def install_from_extracted_folder(
    mcp_root: Path, *, progress_cb: ProgressCb = None, install_version: str | None = None,
    accepted_source: tuple[str, str] | None = None, accepted_manifest_hash: str = "",
) -> dict:
    """Install or update an MCP from an already-extracted folder.

    The folder must contain a ``manifest.json`` at its root. Subdirectories
    listed in ``_PRESERVE_DIRS`` are kept across updates so a re-install
    doesn't blow away ``node_modules`` / ``venv`` / per-instance state. A
    folder present with no registry entry (a remnant) is backed up and
    replaced the same way and restored on failure; one that holds another MCP
    is refused (409) before any file moves.

    ``progress_cb`` (optional) receives job-level ``{phase, pct, message}``
    events through the install — used by the async admin-install background job
    to drive the dashboard progress bar. Default ``None`` leaves the zip-upload
    endpoint and any other caller unchanged.

    ``install_version`` (optional) pins the exact node/python version to install
    (the update path resolves the bounded target and passes it here). When
    unset, a fresh install resolves the catalog ``server.version_constraint`` (if
    any) to the latest in-bound version, installs an already-pinned ``source``
    verbatim, or installs the bare latest. Ignored for docker/git+.

    ``accepted_source`` (the admin's switch, ``mcp_source_swap.switch``) lets
    the incoming folder change the installed source identity to exactly that
    pair, and ``accepted_manifest_hash`` pins the catalog manifest the admin
    saw: a folder whose manifest hashes differently is refused (409) before
    any file moves. A switch drops ``node_modules`` and ``venv`` after the
    backup and stops a container the incoming runtime no longer has.

    Raises ``HTTPException`` on validation or install failure. Returns a
    dict matching the existing zip-upload endpoint's response shape so the
    frontend can reuse its install-result UI, plus ``container_started``
    (the auto-start's outcome for a container runtime, ``None`` otherwise).
    """
    manifest_data = await asyncio.to_thread(_check_incoming_tree, mcp_root)

    errors = _validate_manifest(manifest_data)
    if errors:
        raise HTTPException(400, f"Invalid manifest: {'; '.join(errors)}")
    # The lexical rule passed above; the file must also exist inside THIS
    # folder as a regular file (a link is judged by its target).
    for sk in manifest_data.get("skills") or []:
        if _mmp.resolve_skill_file(mcp_root, sk["file"]) is None:
            raise HTTPException(
                400,
                f"Invalid manifest: skill {sk['id']}: file {sk['file']!r} is "
                "not a regular file inside the MCP folder",
            )
    compose_file = manifest_data["server"].get("docker_compose") or ""
    rt = _mt.runtime_of(manifest_data["server"].get("runtime"))
    if rt is not None and rt.container and compose_file:
        if _mmp.resolve_skill_file(mcp_root, compose_file) is None:
            raise HTTPException(
                400,
                f"Invalid manifest: server.docker_compose {compose_file!r} is "
                "not a regular file inside the MCP folder",
            )

    mcp_name = manifest_data["name"]
    category = manifest_data["category"]
    runtime = manifest_data["server"].get("runtime", "")  # absent on remote MCPs
    source = manifest_data["server"].get("source", "")
    version = manifest_data.get("version", "unknown")

    if category != "community":
        raise HTTPException(
            400,
            "Only community MCPs can be installed via this path. Core and "
            "custom MCPs ship with the platform. (Skill packages install via "
            "the skills catalog.)",
        )

    target_parent = config.MCPS_DIR / category
    target_parent.mkdir(parents=True, exist_ok=True)

    existing = mcp_registry.get_manifest(mcp_name)
    is_update = existing is not None
    # Flat-namespace guards (mirrored in skills_installer): an MCP whose name
    # is an installed SKILL PACKAGE, or whose skills[] ids collide with
    # another provider's, is rejected up front — the registry scan would
    # otherwise warn-and-shadow nondeterministically.
    if existing is not None and existing.category == "skill":
        raise HTTPException(
            409,
            f"Name {mcp_name!r} is already an installed skill package — "
            "MCPs and skill packages share the flat registry namespace",
        )
    if existing is not None and existing.category != "community":
        raise HTTPException(
            409,
            f"Name {mcp_name!r} is already a {existing.category} MCP shipped "
            "with the platform",
        )
    if existing is not None:
        _refuse_source_change(
            mcp_name, existing.server, manifest_data["server"], accepted=accepted_source,
        )
    switching = accepted_source is not None and existing is not None
    if switching and accepted_manifest_hash:
        from services.community import community_catalog
        if community_catalog.normalized_manifest_hash(manifest_data) != accepted_manifest_hash:
            raise HTTPException(
                409,
                f"The catalog entry of `{mcp_name}` changed since the check. Run "
                "Check updates and look at the change again.",
            )
    for _sk in manifest_data.get("skills") or []:
        _provider = mcp_registry.find_skill_provider(_sk.get("id", ""))
        if _provider is not None and _provider.name != mcp_name:
            raise HTTPException(
                409,
                f"Skill id {_sk.get('id')!r} is already provided by "
                f"{_provider.name!r}",
            )
    if rt is not None and rt.container:
        await asyncio.to_thread(_check_incoming_compose, mcp_root, mcp_name)
    # A switch away from a container runtime stops the container now, while
    # its compose file is still in place; a container-to-container switch is
    # replaced by the force-recreate start below. Nothing is torn down before
    # the gate above has passed.
    stopped_container = None
    if switching and _mt.is_container(existing.server) and not (rt is not None and rt.container):
        from services.mcp import docker_manager
        await asyncio.to_thread(docker_manager.stop_container, existing)
        stopped_container = existing
    old_version = existing.version if existing else None
    # Snapshot the prior enabled state. On update we'll restore it post-scan;
    # on new install we'll force enabled=True so the admin doesn't have to
    # flip the platform-enable toggle after an explicit "install" action.
    prior_enabled = _existing_enabled_state(mcp_name) if is_update else None

    folder_name = existing.mcp_dir.name if is_update else re.sub(
        r"[^a-zA-Z0-9_-]", "-", mcp_name,
    )
    target_dir = target_parent / folder_name
    if not is_update and target_dir.exists():
        # A folder with no registry entry for this name is replaced like an
        # update below; one that belongs to another MCP is never touched.
        owner = await asyncio.to_thread(_remnant_owner, target_dir, mcp_name)
        if owner:
            raise HTTPException(
                409,
                f"The folder {target_dir.name!r} already holds the MCP {owner!r}. "
                "Uninstall it first, or install this MCP under another name.",
            )

    # An existing folder (an update, or a remnant): take a sibling backup for
    # rollback, then replace only the non-preserved files. On a new folder:
    # just copy. All synchronous FS work runs off the event loop (this
    # function can run as a background install task), so a large
    # copytree/rmtree can't stall the loop.
    await _emit(progress_cb, "prepare", 15, "Preparing files")
    backup_dir: Path | None = None
    if target_dir.exists():
        backup_dir = target_dir.with_suffix(".bak")
    async def _undo_teardown() -> None:
        # After a rollback the old compose file is back: the container a
        # switch stopped is started again, best effort, unless the MCP was
        # disabled and its container down on purpose.
        if stopped_container is None or prior_enabled is False:
            return
        from services.mcp import docker_manager
        try:
            await asyncio.to_thread(docker_manager.start_container, stopped_container)
        except Exception as exc:
            logger.warning("Restart of %s after a failed switch failed: %s", mcp_name, exc)

    try:
        await asyncio.to_thread(
            _apply_extracted_files, mcp_root, target_dir, is_update, backup_dir,
            drop_runtime_dirs=switching,
        )

        # Run the package install (npm / pip / docker). The shared
        # ``mcp_installer`` is the same one the satellite uses.
        install_log = ""
        install_ok = True
        resolved_version = ""
        container_started: bool | None = None
        # remote: MCPs are vendor-hosted — the folder copy above IS the install
        # (manifest registration only), so skip the package-install step.
        if source and not source.startswith("remote:"):
            # Effective install source for node/python. The catalog source is unpinned
            # (`npm:pkg` / `pypi:pkg`); pick the exact version to install:
            #   • install_version given (update path) → that version;
            #   • catalog declares a version_constraint (fresh install) → latest in-bound;
            #   • source already pinned (e.g. a zip upload `npm:pkg@1.0.0`) → as-is;
            #   • otherwise → bare source (install_mcp installs the latest).
            # docker/git+ are installed verbatim (constraint/install_version ignored).
            from services.mcp import mcp_updater
            parsed = mcp_installer.parse_source(source)
            effective_source = source
            if parsed and parsed.registry in ("npm", "pypi"):
                if install_version:
                    effective_source = f"{parsed.registry}:{parsed.package}@{install_version}"
                elif not parsed.version:
                    constraint = manifest_data["server"].get("version_constraint", "") or ""
                    if constraint:
                        target = await mcp_updater.resolve_latest_in_bound(
                            parsed.registry, parsed.package, constraint,
                        )
                        if not target:
                            if backup_dir and backup_dir.exists():
                                await asyncio.to_thread(
                                    _rollback_extracted_files, target_dir, backup_dir,
                                )
                            await _undo_teardown()
                            raise HTTPException(
                                502,
                                f"No published {parsed.registry} version of "
                                f"'{parsed.package}' satisfies the catalog version "
                                f"constraint {constraint!r}.",
                            )
                        effective_source = f"{parsed.registry}:{parsed.package}@{target}"

            # Map mcp_installer's intra-step pct (npm/venv/pip, 0-100) into the job's
            # 20-80 "installing dependencies" band. A no-op for docker — install_mcp
            # returns instantly there; the real docker work (pull/start) is below.
            async def _install_progress(ev: dict) -> None:
                sub = ev.get("pct") or 0
                mapped = 20 + int(sub * 0.6)
                await _emit(
                    progress_cb, "install", mapped,
                    ev.get("message") or ev.get("phase") or "Installing dependencies",
                )
            try:
                result = await mcp_installer.install_mcp(
                    target_dir, runtime, effective_source,
                    progress_cb=_install_progress,
                    uv_bin=_uv_bin_if_present(),
                    timeout=_INSTALL_TIMEOUT_SECONDS,
                    source_build=list(manifest_data["server"].get("source_build") or []),
                )
                install_ok, install_log = result.ok, result.log
                resolved_version = result.resolved_version
            except asyncio.TimeoutError as exc:
                install_ok, install_log = False, f"Install timed out: {exc}"

        if not install_ok:
            if backup_dir and backup_dir.exists():
                await asyncio.to_thread(_rollback_extracted_files, target_dir, backup_dir)
            await _undo_teardown()
            raise HTTPException(
                500,
                f"Install failed — rolled back.\n\n{install_log}",
            )
    except HTTPException:
        raise
    except Exception:
        # Anything the explicit paths above did not catch (a copy error, a
        # spawn failure): the folder and the container come back before the
        # error leaves, so a retry meets the install as it was.
        if backup_dir and backup_dir.exists():
            await asyncio.to_thread(_rollback_extracted_files, target_dir, backup_dir)
        await _undo_teardown()
        raise

    if backup_dir and backup_dir.exists():
        await asyncio.to_thread(shutil.rmtree, backup_dir, ignore_errors=True)

    # Pin the LOCAL manifest for unpinned node/python installs (the catalog
    # carries no version for these — see services/mcp/mcp_updater.pin_local_manifest).
    # Best-effort: the install already succeeded and the backup is gone, so a pin
    # write failure must not fail the install — it self-heals on the next update.
    parsed = mcp_installer.parse_source(source) if source else None
    if parsed and parsed.registry in ("npm", "pypi") and resolved_version:
        try:
            from services.mcp import mcp_updater
            await asyncio.to_thread(
                mcp_updater.pin_local_manifest,
                target_dir, parsed.registry, parsed.package, resolved_version,
            )
            version = resolved_version
        except Exception as exc:
            logger.warning("Failed to pin local manifest for %s: %s", mcp_name, exc)
    # Never surface an empty version (unpinned catalog manifest reports "");
    # a readback miss leaves it unpinned but the UI should still show something.
    version = version or "latest"

    # Pick up the new manifest in the in-process registry, then regenerate
    # the Docker .env so the container picks up current platform values
    # without waiting for a proxy restart or enable-toggle.
    mcp_registry.scan_manifests()

    # Auto-enable on new install. On update, restore whatever the admin had
    # previously chosen (scan_manifests defaults community→disabled, which
    # would silently re-disable an MCP that was already enabled). For Docker
    # MCPs the .env regeneration below also runs only when enabled, so order
    # matters.
    from storage.mcp import mcp_store
    if is_update and prior_enabled is not None:
        await asyncio.to_thread(mcp_store.set_mcp_enabled, mcp_name, prior_enabled)
    elif not is_update:
        await asyncio.to_thread(mcp_store.set_mcp_enabled, mcp_name, True)

    refreshed = mcp_registry.get_manifest(mcp_name)

    # Default a relay-capable OAuth MCP to the OtoDock hosted relay so it works
    # out of the box. Relay-capable = the manifest declares a top-level
    # ``hosted.oauth_app`` that is available; if the relay is available it should
    # be the default (that is the whole point — no BYO OAuth app needed). We
    # persist the explicit ``_hosted_service_mode`` value rather than relying on
    # the manifest-``default_mode`` fallback (some read paths skip that fallback,
    # which is why a fresh install otherwise lands on self-managed). Only set it
    # when the admin hasn't already chosen a mode — so this never clobbers an
    # explicit choice and is a safe no-op on update.
    if (
        refreshed
        and refreshed.hosted
        and refreshed.hosted.oauth_app
        and refreshed.hosted.oauth_app.available
    ):
        existing_mode = await asyncio.to_thread(
            mcp_store.get_mcp_config_value, mcp_name, "_hosted_service_mode"
        )
        if existing_mode is None:
            await asyncio.to_thread(
                mcp_store.set_mcp_config_value, mcp_name, "_hosted_service_mode", "hosted"
            )
            logger.info("Defaulted relay-capable MCP %s to hosted OAuth", mcp_name)

    if refreshed and _mt.is_container(refreshed.server):
        try:
            from services.mcp import docker_manager
            await asyncio.to_thread(docker_manager._inject_mcp_env, refreshed)
        except Exception as exc:
            logger.warning("Failed to populate .env after install for %s: %s", mcp_name, exc)
        # T2: write the pull-form rewrite now. Its refusals were already
        # judged on the incoming folder, before any file moved
        # (_check_incoming_compose); idempotent, a no-op on bare-metal T1.
        try:
            from services.mcp import compose_rewrite
            await asyncio.to_thread(compose_rewrite.ensure_pull_compose, refreshed)
        except ValueError as exc:
            raise HTTPException(
                400,
                f"'{mcp_name}' cannot be installed in Docker-Compose mode: {exc}",
            )
        except Exception as exc:
            logger.warning("Compose pre-rewrite skipped for %s: %s", mcp_name, exc)
        # T2 only: the boot-time startup_docker_mcps skips community Docker MCPs,
        # so a runtime install has no other trigger to actually start the pulled
        # container — start it here when the MCP is enabled. Best-effort: a slow
        # first pull or a transient failure doesn't fail the install (the admin
        # can retry via restart). T1 is unchanged — startup_docker_mcps / the
        # admin start it there.
        from core.config import deployment
        enabled_now = True if not is_update else bool(prior_enabled)
        # Auto-start the container after install on every self-host topology —
        # T1 bare-metal AND T2 socket-proxy; only cloud (external-pool) has no
        # local container. start_container pulls (or builds, T1 fallback) + brings
        # it up, so the slow opaque fetch shows as the "image" phase on both.
        if enabled_now and deployment.current_mode() != deployment.EXTERNAL_POOL:
            await _emit(
                progress_cb, "image", 40,
                "Fetching image — large images can take a few minutes…",
            )
            try:
                # On an UPDATE, force-recreate so the running container is
                # replaced; start_container refreshes the image either way (a
                # same-tag rebuild or moved tag wouldn't be re-pulled by a
                # plain recreate).
                started = await asyncio.to_thread(
                    docker_manager.start_container, refreshed,
                    force_recreate=is_update,
                )
                logger.info("Auto-start %s after install: ok=%s", mcp_name, started)
                container_started = bool(started)
            except Exception as exc:
                logger.warning("Auto-start of %s after install failed: %s", mcp_name, exc)
                container_started = False
            await _emit(progress_cb, "start", 90, "Starting container")

    await _emit(progress_cb, "finalize", 95, "Finalizing")
    return {
        "status": "updated" if is_update else "installed",
        "name": mcp_name,
        "version": version,
        "old_version": old_version,
        "runtime": runtime,
        "install_log": install_log,
        "container_started": container_started,
    }


def _uv_bin_if_present() -> str | None:
    """Return path to ``uv`` if present, else ``None``."""
    import os
    uv = os.path.expanduser("~/.local/bin/uv")
    return uv if os.path.isfile(uv) else None


def _existing_enabled_state(mcp_name: str) -> bool | None:
    """Return the current ``mcp_state.enabled`` for an MCP, or ``None`` if no row exists."""
    from storage.mcp import mcp_store
    state = mcp_store.get_mcp_state(mcp_name)
    return state.get("enabled") if state else None


# ---------------------------------------------------------------------------
# Catalog install — fetch from GitHub, then call the shared pipeline
# ---------------------------------------------------------------------------

async def install_from_catalog(
    name: str, *, progress_cb: ProgressCb = None, install_version: str | None = None,
    accepted_source: tuple[str, str] | None = None, accepted_manifest_hash: str = "",
) -> dict:
    """Download one MCP folder from ``OtoDock/community-mcps`` and install it.

    Fetches the whole-repo tarball (small — ~50KB at the time of writing),
    extracts just the ``<name>/`` subfolder, hands it to
    :func:`install_from_extracted_folder`. Raises ``HTTPException`` on fetch
    or install failure.

    ``progress_cb`` (optional) is threaded through for live install progress;
    default ``None`` leaves the manager-request/approve caller unchanged.
    ``install_version`` (optional) pins the exact node/python version to install
    (the converge-update path passes the bounded target). ``accepted_source``
    and ``accepted_manifest_hash`` are the admin's switch (see
    :func:`install_from_extracted_folder`).
    """
    if not _is_safe_name(name):
        # Defense-in-depth — endpoint also validates, but the path is built
        # below by string interpolation against the tarball entries, so any
        # callable into this function gets the same check.
        raise HTTPException(400, f"Invalid MCP name: {name!r}")

    from services.community import community_catalog
    try:
        registry = await community_catalog.fetch_registry()
        _entry = next(
            (e for e in registry.get("mcps", []) if e.get("name") == name),
            None,
        )
    except Exception:
        _entry = None
    if _entry is not None:
        community_catalog.require_platform_compat(
            name, _entry.get("platform_min_version"),
        )

    await _emit(progress_cb, "fetch", 5, "Downloading from catalog")
    tarball = await _fetch_catalog_tarball()

    tmp = Path(tempfile.mkdtemp(prefix="mcp-catalog-install-"))
    try:
        # Extract just the target MCP's folder. GitHub tarballs prefix every
        # path with ``<owner>-<repo>-<sha>/`` so we walk to find the entry
        # that matches ``<prefix>/<name>/``.
        mcp_root = await asyncio.to_thread(
            _extract_mcp_subfolder, tarball, name, tmp,
        )
        if mcp_root is None:
            raise HTTPException(
                404,
                f"MCP '{name}' not found in catalog tarball. The catalog may "
                "have been updated since the last list refresh.",
            )

        return await install_from_extracted_folder(
            mcp_root, progress_cb=progress_cb, install_version=install_version,
            accepted_source=accepted_source,
            accepted_manifest_hash=accepted_manifest_hash,
        )
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def _is_safe_name(name: str) -> bool:
    """Allow only ``[a-z0-9_-]`` so a malicious name can't escape the
    tarball-extraction path or sneak ``..`` into target paths."""
    return bool(re.fullmatch(r"[a-z0-9][a-z0-9_-]*", name))


async def _fetch_catalog_tarball(url: str = CATALOG_TARBALL_URL) -> bytes:
    """GET a catalog repo tarball as raw bytes (community-mcps by default;
    the skills installer passes its own catalog URL)."""
    headers = {
        "Accept": "application/vnd.github+json",
        "User-Agent": "otodock-platform/community-installer",
    }
    try:
        async with httpx.AsyncClient(
            timeout=TARBALL_FETCH_TIMEOUT_SECONDS,
            follow_redirects=True,
        ) as client:
            resp = await client.get(url, headers=headers)
        resp.raise_for_status()
        return resp.content
    except httpx.HTTPError as exc:
        raise HTTPException(
            502,
            f"Could not fetch community catalog tarball: {exc}. "
            "Check network access to api.github.com / codeload.github.com.",
        )


def _extract_mcp_subfolder(tarball: bytes, mcp_name: str, dest: Path) -> Path | None:
    """Extract the catalog folder for ``mcp_name`` from the repo tarball into ``dest``.

    The folder usually shares the MCP's name, but the authoritative id is the
    ``name`` inside each folder's ``manifest.json`` and the two can differ —
    the catalog folder ``workspace-mcp`` ships manifest name
    ``google-workspace`` — so when no folder matches the name directly, fall
    back to scanning the top-level manifests for the matching name. Returns
    the path to the extracted MCP folder, or ``None`` when neither lookup
    matches.
    """
    # Tarball layout: <owner>-<repo>-<sha>/<folder>/...
    with tarfile.open(fileobj=io.BytesIO(tarball), mode="r:gz") as tf:
        # Detect the prefix dir from the first member.
        members = tf.getmembers()
        if not members:
            return None
        prefix = members[0].name.split("/", 1)[0]
        folder = mcp_name
        if not any(
            m.name == f"{prefix}/{folder}" or m.name.startswith(f"{prefix}/{folder}/")
            for m in members
        ):
            folder = _folder_for_manifest_name(tf, members, prefix, mcp_name)
            if folder is None:
                return None
        prefix_with_mcp = f"{prefix}/{folder}/"

        wanted: list[tarfile.TarInfo] = []
        for m in members:
            if m.name == f"{prefix}/{folder}" or m.name.startswith(prefix_with_mcp):
                # Strip the prefix from the entry name so extraction lands
                # under ``dest/`` directly with no nested ``<sha>/`` wrapper.
                stripped = m.name[len(prefix) + 1:]
                if not stripped:
                    continue
                # Path-traversal guard: a clean relative name, joined below
                # the destination (never the raw member name).
                if stripped.startswith("/"):
                    raise HTTPException(400, f"Invalid tarball entry: {m.name}")
                try:
                    stripped = path_confinement.normalize_rel_path(stripped)
                    target_path = path_confinement.join_under(dest, stripped)
                except path_confinement.PathOutsideRoot:
                    raise HTTPException(400, f"Invalid tarball entry: {m.name}")
                m_copy = tarfile.TarInfo(name=stripped)
                m_copy.type = m.type
                m_copy.mode = m.mode
                m_copy.uid = m.uid
                m_copy.gid = m.gid
                m_copy.size = m.size
                m_copy.mtime = m.mtime
                m_copy.linkname = m.linkname
                wanted.append(m_copy)
                # Extract right away while we still have the source member.
                src = tf.extractfile(m) if m.isfile() else None
                if m.isdir():
                    target_path.mkdir(parents=True, exist_ok=True)
                elif m.isfile() and src is not None:
                    target_path.parent.mkdir(parents=True, exist_ok=True)
                    with target_path.open("wb") as out:
                        shutil.copyfileobj(src, out)
                elif m.issym() or m.islnk():
                    # We don't expect symlinks in catalog MCPs. Skip rather
                    # than raise so a stray symlink doesn't block install.
                    logger.warning("Skipping link entry in catalog tarball: %s", m.name)

        if not wanted:
            return None

    mcp_dir = dest / folder
    return mcp_dir if mcp_dir.is_dir() else None


def _folder_for_manifest_name(
    tf: tarfile.TarFile, members: list, prefix: str, mcp_name: str,
) -> str | None:
    """Top-level tarball folder whose ``manifest.json`` declares ``name == mcp_name``."""
    for m in members:
        parts = m.name.split("/")
        if len(parts) == 3 and parts[2] == "manifest.json" and m.isfile():
            src = tf.extractfile(m)
            if src is None:
                continue
            try:
                data = json.loads(src.read().decode("utf-8"))
            except (ValueError, UnicodeDecodeError):
                continue
            if data.get("name") == mcp_name:
                return parts[1]
    return None


