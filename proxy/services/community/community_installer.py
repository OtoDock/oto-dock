async def ensure_enabled_and_running(mcp_name: str) -> str:
    """Converge platform state after an approval: enabled + (Docker) running.

    ``approve_request`` marks a request ``installed`` even when the fetch was
    skipped because the manifest folder already existed on disk (repo-shipped
    ``mcps/community/*``, a previously disabled MCP, a rolled-back attempt).
    ``scan_manifests`` seeds community MCPs at ``enabled=False`` and nothing
    on that path enabled the MCP or started its container — the request
    landed ``installed`` while the MCP stayed invisible at runtime. An
    approval (queue approve, admin auto-approve, the instance-save retry
    sweep, the community-agent template cascade) is an explicit "make this
    usable" decision, so converge unconditionally; a platform-wide re-enable
    of a deliberately disabled MCP is surfaced in the returned note, never
    silent.

    Returns an annotation for the request's ``install_log`` ("" when there
    is nothing noteworthy). Never raises — start problems are recorded, not
    fatal, matching the installer's best-effort auto-start. Idempotent after
    a fresh ``install_from_catalog`` (env re-inject is idempotent and a
    running container is left alone).
    """
    from storage.mcp import mcp_store

    notes: list[str] = []
    prior = _existing_enabled_state(mcp_name)
    if prior is not True:
        await asyncio.to_thread(mcp_store.set_mcp_enabled, mcp_name, True)
        if prior is False:
            notes.append("Re-enabled platform-wide (was disabled).")

    manifest = mcp_registry.get_manifest(mcp_name)
    from core.config import deployment
    if (
        manifest is not None
        and _mt.is_container(manifest.server)
        and deployment.current_mode() != deployment.EXTERNAL_POOL
    ):
        from services.mcp import docker_manager
        try:
            await asyncio.to_thread(docker_manager._inject_mcp_env, manifest)
        except Exception as exc:
            logger.warning(".env refresh failed for %s: %s", mcp_name, exc)
        try:
            from services.mcp import compose_rewrite
            await asyncio.to_thread(compose_rewrite.ensure_pull_compose, manifest)
        except ValueError as exc:
            # Approval context records the problem instead of failing the
            # request; the direct-install route keeps its hard 400.
            notes.append(f"Compose rewrite failed: {exc}")
        except Exception as exc:
            logger.warning("Compose pre-rewrite skipped for %s: %s", mcp_name, exc)
        status = await asyncio.to_thread(
            docker_manager.get_container_status, manifest,
        )
        if status not in docker_manager.STARTED:
            try:
                started = await asyncio.to_thread(
                    docker_manager.start_container, manifest,
                )
                logger.info(
                    "Auto-start %s after approval: ok=%s", mcp_name, started,
                )
                if not started:
                    notes.append(
                        "Container did not start — check Admin → MCP Servers.",
                    )
            except Exception as exc:
                logger.warning(
                    "Auto-start of %s after approval failed: %s", mcp_name, exc,
                )
                notes.append(f"Container start failed: {exc}")
    return "\n".join(notes)


async def approve_request(
    request_id: int,
    admin_sub: str,
    admin_note: str = "",
    instance_id: int | None = None,
) -> dict:
    """Approve an assignment request: install if needed + enable for agent.

    Returns the updated request row. Status transitions:

    - ``pending → approved → installing → installed`` on success
    - ``pending → approved → installing → install_failed`` on install error
      (the admin can retry later via the same endpoint).

    The MCP is enabled for the requesting agent (``mcp_store.add_agent_mcp``)
    only after the install completes successfully. Notifies the requester
    once the request resolves.

    ``instance_id`` (explicit-mode MCPs only) pins the instance the agent is
    attached to; ``None`` keeps the automatic pick (catch-all / already
    attached / lowest-id). Validated BEFORE any status transition — a 400
    mid-cascade would strand the row in ``installing``, a state the
    transition table only exits via installed/install_failed. Consequently
    ``instance_id`` requires the MCP to already be installed and
    explicit-mode; for a not-yet-installed MCP the admin approves without it
    and the needs-instance retry offers the selector.
    """
    from storage.mcp import mcp_request_store
    from storage.mcp import mcp_store

    req = await asyncio.to_thread(mcp_request_store.get_request, request_id)
    if req is None:
        raise HTTPException(404, f"Request {request_id} not found")
    if req["status"] not in mcp_request_store.APPROVABLE:
        raise HTTPException(
            409,
            f"Cannot approve request in status {req['status']!r}",
        )

    if instance_id is not None:
        manifest = mcp_registry.get_manifest(req["mcp_name"])
        if manifest is None or getattr(manifest, "assignment_mode", "auto") != "explicit":
            raise HTTPException(
                400,
                "instance_id only applies to installed explicit-mode MCPs "
                f"('{req['mcp_name']}' is "
                f"{'not installed' if manifest is None else 'auto-mode'})",
            )
        _instances = await asyncio.to_thread(
            mcp_store.get_mcp_instances, req["mcp_name"],
        )
        if not any(int(i["id"]) == instance_id for i in _instances):
            raise HTTPException(
                400,
                f"Instance {instance_id} does not belong to MCP "
                f"'{req['mcp_name']}'",
            )

    # pending → approved → installing in one shot (avoid two notifications).
    if req["status"] == mcp_request_store.PENDING:
        await asyncio.to_thread(
            mcp_request_store.update_status,
            request_id, mcp_request_store.APPROVED, resolved_by=admin_sub, admin_note=admin_note,
        )
    req = await asyncio.to_thread(
        mcp_request_store.update_status, request_id, mcp_request_store.INSTALLING,
    )

    mcp_name = req["mcp_name"]
    agent_slug = req["agent_slug"]
    kind = req.get("kind") or "mcp"

    install_log = ""
    install_failed_msg: str | None = None
    try:
        # Skip the install when the MCP is already on disk and at the current
        # catalog version — the registry's ``get_manifest`` returns ``None``
        # only when the folder is absent. Serialize on the per-MCP install lock
        # so a concurrent direct admin install of the same MCP can't race this
        # on the install dir; re-check inside the lock (the other install may
        # have just landed it while we waited, in which case we no-op).
        from core.credentials import catalog_install_registry
        async with catalog_install_registry.lock_for(mcp_name):
            if mcp_registry.get_manifest(mcp_name) is None:
                if kind == "skill":
                    from services.community import skills_installer
                    install_result = await (
                        skills_installer.install_skill_package_from_catalog(mcp_name)
                    )
                else:
                    install_result = await install_from_catalog(mcp_name)
                install_log = install_result.get("install_log", "")
            else:
                install_log = "Already installed — skipping fetch + dependency install."
    except HTTPException as exc:
        install_failed_msg = exc.detail if isinstance(exc.detail, str) else str(exc.detail)
    except Exception as exc:
        logger.exception("Unexpected install error for %s", mcp_name)
        install_failed_msg = f"{type(exc).__name__}: {exc}"

    if install_failed_msg:
        updated = await asyncio.to_thread(
            mcp_request_store.update_status,
            request_id, mcp_request_store.INSTALL_FAILED,
            install_log=install_failed_msg,
        )
        # ``install_failed`` is non-terminal (admin may retry) — don't fire
        # the batch-complete roll-up here; only the per-request failure
        # notification, which the batched path also wants to receive so the
        # admin sees the error inline.
        await _notify_request_failed(updated)
        return updated

    # Install OK → converge platform state. The skip branch above never
    # enabled the MCP or started its container ("manifest on disk" is not
    # "enabled and running"), so an approved repo-shipped or previously
    # disabled MCP would otherwise stay invisible at runtime.
    converge_note = await ensure_enabled_and_running(mcp_name)
    if converge_note:
        install_log = (install_log + "\n" if install_log else "") + converge_note

    # Assign the MCP to the agent. ``add_agent_mcp`` is idempotent so a
    # re-request after a previous installed state is safe.
    await asyncio.to_thread(mcp_store.add_agent_mcp, agent_slug, mcp_name)

    # Seed agent_skills rows for the assignment (idempotent), mirroring the
    # manager-enable path — without this an approved MCP's/package's skills
    # have no rows for the Skills tab to toggle until the next manual save.
    _m = mcp_registry.get_manifest(mcp_name)
    for _skill in getattr(_m, "skills", None) or []:
        await asyncio.to_thread(
            mcp_store.ensure_agent_skill,
            agent_slug, _skill.id, True, _skill.default_exclude_from,
        )

    # For explicit-mode MCPs (prometheus, ssh-server, unifi-network, etc.),
    # the manager-enabled flag alone isn't enough — the runtime only
    # delivers env to an agent if at least one ``mcp_instances`` row
    # authorizes them. Make sure that's true before declaring success.
    instance_status, instance_detail = await asyncio.to_thread(
        _ensure_agent_authorized_for_instance_mcp, mcp_name, agent_slug,
        instance_id,
    )
    if instance_status == "no_instances":
        # Roll the agent_mcps assignment back so the manager UI doesn't
        # show a non-functional row. The install itself is fine; only
        # per-agent authorization is missing.
        await asyncio.to_thread(mcp_store.remove_agent_mcp, agent_slug, mcp_name)
        admin_guidance = (
            f"MCP '{mcp_name}' requires an instance configuration before it "
            f"can be authorized for an agent. Create an instance via "
            f"Admin → MCP Servers → {mcp_name} → Instances (give it credentials "
            f"and optionally tick 'Assign to all agents'), then retry this "
            f"approval."
        )
        updated = await asyncio.to_thread(
            mcp_request_store.update_status,
            request_id, mcp_request_store.INSTALL_FAILED,
            install_log=admin_guidance,
        )
        await _notify_request_failed(updated)
        return updated

    if instance_detail:
        install_log = (install_log + "\n" if install_log else "") + instance_detail

    updated = await asyncio.to_thread(
        mcp_request_store.update_status,
        request_id, mcp_request_store.INSTALLED,
        resolved_by=admin_sub,
        install_log=install_log,
    )
    # Batched rows: suppress the per-request approve notification — the
    # requester gets a single roll-up via _maybe_notify_batch_complete once
    # every row in the batch reaches a terminal state.
    if updated.get("batch_id"):
        await _maybe_notify_batch_complete(updated)
    else:
        await _notify_request_approved(updated)
    return updated


def _ensure_agent_authorized_for_instance_mcp(
    mcp_name: str, agent_slug: str, instance_id: int | None = None,
) -> tuple[str, str]:
    """Make sure an explicit-mode MCP authorizes ``agent_slug`` via at least one
    instance. No-op for non-explicit (auto-mode) MCPs.

    Returns (status, human_log) where status is one of:

    - ``"not_applicable"`` — MCP is auto-mode; nothing to do.
    - ``"added_to_selected"`` — admin chose an instance on approval; the
      agent was attached to exactly that one. An explicit choice wins over
      the catch-all/already-attached shortcuts — the admin said where the
      agent goes. (The id was validated against this MCP's instances before
      any status transition, so a vanished instance here means it was
      deleted mid-approve — that falls through to the automatic path.)
    - ``"assigned_to_all"`` — a catch-all instance already authorizes everyone.
    - ``"already_authorized"`` — agent was already in some instance's list.
    - ``"added_to_first"`` — agent was attached to the lowest-id instance
      (matches the runtime precedence in
      :func:`mcp_store.get_instance_for_agent_env_delivery`). Admin can move
      the agent to a different instance via the Instances UI if desired.
    - ``"no_instances"`` — explicit-mode MCP with zero instances. Caller
      should treat this as a soft failure and prompt the admin to create
      one before retrying.

    The ``human_log`` is a one-line description suitable for appending to
    the request's ``install_log``.
    """
    from storage.mcp import mcp_store

    manifest = mcp_registry.get_manifest(mcp_name)
    # ``getattr`` with default so test-stub manifests (bare ``object()``)
    # naturally fall through to "not applicable" rather than raising.
    if not manifest or getattr(manifest, "assignment_mode", "auto") != "explicit":
        return ("not_applicable", "")

    instances = mcp_store.get_mcp_instances(mcp_name)
    if not instances:
        return ("no_instances", "")

    if instance_id is not None:
        chosen = next(
            (i for i in instances if int(i["id"]) == instance_id), None,
        )
        if chosen is not None:
            mcp_store.add_agent_to_instance(chosen["id"], agent_slug)
            return (
                "added_to_selected",
                f"Attached agent to instance '{chosen['instance_name']}' "
                f"(admin-selected on approval).",
            )
        # Deleted between validation and here — automatic path below.

    if any(i["assigned_to_all"] for i in instances):
        return ("assigned_to_all", f"Authorized via catch-all instance.")

    if any(agent_slug in i["agents"] for i in instances):
        return ("already_authorized", f"Agent already attached to an instance.")

    target = sorted(instances, key=lambda i: i["id"])[0]
    mcp_store.add_agent_to_instance(target["id"], agent_slug)
    return (
        "added_to_first",
        f"Attached agent to instance '{target['instance_name']}' "
        f"(lowest id; admin can reassign via Instances UI).",
    )


async def reject_request(request_id: int, admin_sub: str, admin_note: str = "") -> dict:
    """Reject a pending request; notifies the requester with the admin's note."""
    from storage.mcp import mcp_request_store
    req = await asyncio.to_thread(mcp_request_store.get_request, request_id)
    if req is None:
        raise HTTPException(404, f"Request {request_id} not found")
    if req["status"] != mcp_request_store.PENDING:
        raise HTTPException(409, f"Cannot reject request in status {req['status']!r}")

    updated = await asyncio.to_thread(
        mcp_request_store.update_status,
        request_id, mcp_request_store.REJECTED,
        resolved_by=admin_sub, admin_note=admin_note,
    )
    if updated.get("batch_id"):
        await _maybe_notify_batch_complete(updated)
    else:
        await _notify_request_rejected(updated)
    return updated


async def cancel_request(request_id: int, user_sub: str) -> dict:
    """Cancel an open pending request. Only the original requester may cancel."""
    from storage.mcp import mcp_request_store
    req = await asyncio.to_thread(mcp_request_store.get_request, request_id)
    if req is None:
        raise HTTPException(404, f"Request {request_id} not found")
    if req["requested_by"] != user_sub:
        raise HTTPException(403, "Only the original requester can cancel")
    if req["status"] != mcp_request_store.PENDING:
        raise HTTPException(409, f"Cannot cancel request in status {req['status']!r}")

    updated = await asyncio.to_thread(
        mcp_request_store.update_status,
        request_id, mcp_request_store.CANCELLED,
        resolved_by=user_sub,
    )
    if updated.get("batch_id"):
        await _maybe_notify_batch_complete(updated)
    return updated


