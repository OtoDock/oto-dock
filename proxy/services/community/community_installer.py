# pin — keep it so the MCP's bridge subnet stays stable across updates. (The Docker
# ``.env`` is regenerated by ``_inject_mcp_env`` each start, so it isn't listed.)
_PRESERVE_FILES = {"docker-compose.override.yml"}

# The bound on each package-manager step of an install (its whole run), the
# installer's own default. Past it the step is killed with everything it
# started and the install rolls back.
_INSTALL_TIMEOUT_SECONDS = mcp_installer.DEFAULT_INSTALL_TIMEOUT


