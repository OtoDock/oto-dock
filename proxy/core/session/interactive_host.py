"""What the terminal session's mixins read off ``self``.

``InteractiveSession`` (``interactive_session.py``) is assembled from a chain of
mixins (input, queue, turn, output), which share the session's state and call
each other's methods through ``self``. A type checker sees each mixin alone, so the
chain's bottom names this Protocol as its base for the type checker only (``if
TYPE_CHECKING``); at run time the base is ``object``, so nothing about the class
changes. A new attribute a mixin reads, or a method one mixin calls on another, is
declared here.
"""

