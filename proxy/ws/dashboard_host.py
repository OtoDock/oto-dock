"""What the dashboard connection's mixins read off ``self``.

``DashboardConnection`` (``ws/dashboard.py``) is assembled from controller
mixins (warmup, chat send/stream/resume/support, PTY viewer, server events,
the dispatcher) that share one connection's state and call each other's
helpers through ``self``. A type checker sees each mixin alone, so every
cross-mixin read used to be an unknown attribute. Each mixin names this
Protocol as its base for the type checker only (``if TYPE_CHECKING``); at run
time the base is ``object``, so nothing about the class changes.

A new attribute the connection sets, or a helper one mixin calls on another,
is declared here.
"""

from __future__ import annotations

import asyncio
import collections
from typing import TYPE_CHECKING, Protocol

if TYPE_CHECKING:
    from auth.providers import UserContext
    from core.events.common_events import TurnInput
    from core.events.stream_pump import ChatStreamPump
    from core.execution_layer import ExecutionLayer
    from services.notifications import notification_manager
    from ws.dashboard import _SpawnResult


class DashboardHost(Protocol):
    _attached_warmups: set[str]
    _client_pushback: collections.deque[str]
    _closed_by_revalidation: bool
    _held_gate: str
    _history_deltas: bool
    _pre_warmed_sid: str | None
    _pre_warmup_task: asyncio.Task | None
    _view_only: bool
    _warmup_task: asyncio.Task | None
    _ws_gone: bool
    agent_name: str
    agent_roles: dict[str, str]
    artifact_queue: list[dict]
    chat_id: str | None
    deferred_for: str
    deferred_mode: str
    deferred_model: str
    implement_queue: list[TurnInput]
    implementing_plan: str
    layer: ExecutionLayer | None
    live_queue: notification_manager.LiveQueue
    notify_connection_id: str
    notify_queue: notification_manager.NotifyQueue
    pending_control_requests: list[tuple[str, dict]]
    pre_plan_mode_holder: list[str]
    session_id: str | None
    streaming: bool
    user: dict
    user_agents: list[str]
    user_role: str
    user_sub: str

    def _announce_sent(self, cid: str, items: list, rows_first: asyncio.Future) -> None: ...
    async def _attach_pty_viewer(self, sess) -> None: ...
    def _build_cancelled_context(
            self, cid: str, *, new_text: str | None=None, new_rows: int=1,
    ) -> str: ...
    def _can_access_agent(self, name: str) -> bool: ...
    def _cancel_artifacts(self, chat_id: str) -> None: ...
    async def _create_or_resume_session(
            self, sid: str, agent: str, perm_mode: str, *, resume: bool=False, model: str='',
            exec_path: str='', resume_handle: str='', chat_id: str='', pinned_target: str='',
            adopt: bool=True, chat_exec_mode: str='', chat_theme: str='', first_prompt: str='',
            focus_line: str='',
    ) -> _SpawnResult: ...
    async def _deny_task_continue(
            self, cid: str | None, chat: dict | None=None, *, quiet: bool=False,
    ) -> str: ...
    def _detach_pty_viewer(self) -> None: ...
    def _deterministic_title(self, text: str) -> str: ...
    async def _dispatch_client_message(self, msg: dict) -> str | None: ...
    async def _drain_live_queue(self) -> None: ...
    def _ensure_bg_monitor(
            self, session: str | None=None, chat: str | None=None,
            layer_: ExecutionLayer | None=None,
    ) -> None: ...
    async def _enter_pump_loop(self) -> ChatStreamPump | None: ...
    async def _flush_pending_control_requests(self): ...
    async def _handle_app_action(self, msg: dict): ...
    async def _handle_artifact_interaction(self, msg: dict): ...
    async def _handle_chat(self, msg: dict): ...
    async def _handle_chat_read(self, msg: dict): ...
    async def _handle_execution_mode_change(self, msg: dict): ...
    async def _handle_implement_plan(self, msg: dict): ...
    async def _handle_mode_change(self, msg: dict): ...
    async def _handle_model_change(self, msg: dict): ...
    async def _handle_pre_warmup(self, msg: dict): ...
    async def _handle_pty_takeover(self, msg: dict) -> None: ...
    async def _handle_resume_chat(self, msg: dict): ...
    async def _handle_switch_execution_mode(self, msg: dict): ...
    async def _handle_warmup(self, msg: dict, *, background: bool=True): ...
    async def _heal_viewed_session(self, msg: dict) -> str: ...
    def _interactive_prelude(
            self, text: str, *, session_id: str='', focus_line: str='',
    ) -> str: ...
    async def _may_drive_terminal(self, isess) -> bool: ...
    async def _may_resolve_permission(self, request_id: str) -> bool: ...
    def _maybe_stop_and_send(self, pump) -> None: ...
    async def _persist_first_prompt(self, cid: str, prompt_text: str) -> None: ...
    async def _pong(self) -> None: ...
    async def _prepare_turn_input(
            self, text: str, images: list[dict], files: list[dict], *,
            session_id: str | None=None,
    ) -> TurnInput | None: ...
    async def _prepared_prompt(
            self, cid: str, cli_text: str, *, new_text: str,
    ) -> tuple[str, dict | None]: ...
    async def _process_attachments(
            self, text: str, images: list[dict], files: list[dict], *, agent: str, agent_dir,
            is_agent_scoped: bool, username: str, is_direct_llm: bool,
    ) -> tuple[str, list[dict], list[dict], list[dict]]: ...
    async def _queue_for_next_turn(
            self, cid: str, item: TurnInput, queue_id=None, *, waiting: str='',
    ) -> None: ...
    def _queue_interaction(
            self, pump: ChatStreamPump, interaction: dict, chat_id: str,
    ) -> bool: ...
    async def _reapply_deferred_after_warmup(
            self, chat_id: str, *, from_warmup: bool=False,
    ) -> None: ...
    async def _receive_client_text(self) -> str: ...
    def _register_notify_queue(self, *, replaces: str=''): ...
    async def _resolve_layer_for_chat_async(self, cid: str) -> ExecutionLayer | None: ...
    @staticmethod
    def _restore_abort_flags(cid: str, consumed: dict | None) -> None: ...
    async def _resume_dead_session_for_chat(
            self, dead_sid: str, t_chat_id: str, layer_for_chat: ExecutionLayer, *, adopt: bool,
    ) -> _SpawnResult: ...
    async def _return_warmup_sends(self, chat_id: str, reason: str) -> None: ...
    def _revalidate_session(self) -> bool: ...
    async def _run_kick_headless(
            self, wcid: str, sid: str | None, text: str, images: list[dict], files: list[dict], *,
            force_headless: bool=False,
    ) -> None: ...
    async def _send(self, data: dict): ...
    async def _send_error(self, msg: str): ...
    async def _send_pty_read_only(self, sess) -> None: ...
    async def _send_reconnecting_line(self, cid: str) -> None: ...
    async def _send_text(self, text: str) -> bool: ...
    async def _sender_refusal(self, cid: str, chat: dict | None=None) -> str: ...
    async def _session_still_holds(self) -> bool: ...
    async def _start_new_stream(
            self, prompt: str, *, target_session_id: str | None, target_chat_id: str,
            target_layer: ExecutionLayer | None, images: list[dict] | None=None,
            headless: bool=False, rows_first: asyncio.Future | None=None,
            reconnect_waited: bool=False,
    ) -> ChatStreamPump | None: ...
    def _target_mismatch_fields(self, chat_id: str) -> dict: ...
    def _viewer_context(self) -> UserContext: ...
