// The settings catalog's two generated outputs, from
// src/components/settings/catalog.ts: the JSON the proxy serves at
// GET /v1/settings/catalog (proxy/api/settings/catalog.json) and the
// platform skill's settings map (the otodock-platform skill's
// references/settings-map.md). `npm run settings:build` writes them; the
// suite calls buildSettingsOutputs() and fails when a checked-in output
// differs. Node reads the catalog with type stripping (22.18 and 24 on, the
// package's engines floor), so the catalog stays a leaf file of plain data.
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { CATALOG, CATALOG_ROLE, KIND, SETTINGS_CATALOG_VERSION } from '../src/components/settings/catalog.ts'
import { AREA_LABELS, SECTION_LABELS, whereOf } from '../src/components/settings/where.ts'

export { AREA_LABELS, SECTION_LABELS, whereOf }

export const DASHBOARD = join(dirname(fileURLToPath(import.meta.url)), '..')
export const REPO = join(DASHBOARD, '..')
export const CATALOG_JSON = 'proxy/api/settings/catalog.json'
export const SETTINGS_MAP = 'mcps/custom/mcps-mcp/skills/otodock-platform/references/settings-map.md'

/** Who changes a row, as a sentence the agent can repeat. */
export function whoOf(entry) {
  if (entry.writes === null) return 'Nobody changes it. The page only shows it.'
  if (entry.writes === CATALOG_ROLE.ADMIN) return 'A platform administrator.'
  return 'Any signed-in person, on their own account.'
}

/** One JSON row: the catalog's fields plus the derived sentences and
 *  whether the chat can show a card for it. The binding rides along so the
 *  proxy can check its routes exist; it holds no value. */
export function jsonRow(entry) {
  const row = {
    id: entry.id, area: entry.area, section: entry.section, group: entry.group, label: entry.label,
    kind: entry.kind, help: entry.help, reads: entry.reads, writes: entry.writes,
    where: whereOf(entry), who: whoOf(entry), card: Boolean(entry.value),
  }
  if (entry.tab) row.tab = entry.tab
  if (entry.names) row.names = [...entry.names]
  if (entry.options) row.options = entry.options.map((o) => ({ value: o.value, label: o.label }))
  if (entry.note) row.note = entry.note
  if (entry.item) row.item = entry.item
  if (entry.value) row.value = entry.value
  return row
}

export function catalogJson() {
  return `${JSON.stringify({ version: SETTINGS_CATALOG_VERSION, entries: CATALOG.map(jsonRow) }, null, 1)}\n`
}

const cell = (s) => String(s ?? '').replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\n/g, ' ')

function kindWord(entry) {
  switch (entry.kind) {
    case KIND.TOGGLE: return 'on or off'
    case KIND.CHOICE: return entry.options ? entry.options.map((o) => o.label).join(' / ') : 'a choice'
    case KIND.TEXT: return 'text'
    case KIND.NUMBER: return 'a number'
    case KIND.ACTION: return 'a button'
    case KIND.ITEM: return `per ${entry.item}`
    case KIND.READONLY: return 'shown only'
    default: return entry.kind
  }
}

function whoShort(entry) {
  if (entry.writes === null) return 'read only'
  if (entry.writes === CATALOG_ROLE.ADMIN) return 'admin'
  return 'any'
}

/** The skill page: one table per section, the rows in page order. */
export function settingsMap() {
  const lines = [
    '# Settings map, generated from the settings catalog',
    '',
    'Every setting a person can name, where it lives, what it does and who changes it.',
    `Generated by \`npm run settings:build\` in the dashboard from the catalog (version ${SETTINGS_CATALOG_VERSION}).`,
    'Never edit this page by hand. The rules a table cannot carry are in `settings-notes.md`:',
    'the roles, the shape of the settings areas, the apps and chats surfaces, the quick answers.',
    '',
    'Columns: the setting as the page labels it, with its other names in brackets, what kind of',
    'control it is, what it does, who changes it (*any* = any signed-in person on their own',
    'account, *admin* = a platform administrator, *read only* = nobody changes it, the page only',
    'shows it), and whether a card in the chat can show it (the settings tool asks for it, the',
    'person changes it in the card).',
    '',
  ]
  const groups = new Map()
  for (const e of CATALOG) {
    const key = `${e.area}\u0000${e.section}\u0000${e.tab ?? ''}`
    if (!groups.has(key)) groups.set(key, [])
    groups.get(key).push(e)
  }
  let area = ''
  for (const entries of groups.values()) {
    const first = entries[0]
    if (first.area !== area) {
      area = first.area
      lines.push(`## ${AREA_LABELS[area]}`, '')
    }
    lines.push(`### ${whereOf(first)}`, '')
    lines.push('| Setting | Control | What it does | Who | Card |', '| --- | --- | --- | --- | --- |')
    for (const e of entries) {
      const names = e.names?.length ? ` (${e.names.join(', ')})` : ''
      const note = e.note ? ` *${e.note}*` : ''
      lines.push(`| **${cell(e.label)}**${cell(names)} \`${e.id}\` | ${cell(kindWord(e))} | ${cell(e.help)}${cell(note)} | ${whoShort(e)} | ${e.value ? 'yes' : 'no'} |`)
    }
    lines.push('')
  }
  return `${lines.join('\n').trimEnd()}\n`
}

/** The outputs by path from the repository root. */
export function buildSettingsOutputs() {
  return new Map([
    [CATALOG_JSON, catalogJson()],
    [SETTINGS_MAP, settingsMap()],
  ])
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const [rel, text] of buildSettingsOutputs()) {
    const path = join(REPO, rel)
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, text)
    process.stdout.write(`wrote ${rel}\n`)
  }
}
